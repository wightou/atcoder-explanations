#include <bits/stdc++.h>
#include <atcoder/all>
using namespace std;
using namespace atcoder;

/////////////////// メイン ///////////////////

int main () {
  
  //////////////////// 入力 ////////////////////

  // 文字列を用意し、入力を受け取る
  string s;
  cin >> s;

  //////////////// 出力変数定義 ////////////////



  //////////////////// 処理 ////////////////////

  // sを1文字ずつ見て、'A'以外なら'.'に変える
  // 範囲for文の参照渡しをして楽にする
  for (char& c : s) {
    if (c!='A') c = '.';
  }

  //////////////////// 出力 ////////////////////

  cout << s << endl;

  //////////////////// 終了 ////////////////////

  return 0;

}