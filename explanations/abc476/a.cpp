#include <bits/stdc++.h>
#include <atcoder/all>
using namespace std;
using namespace atcoder;

/////////////////// メイン ///////////////////

int main () {
  
  //////////////////// 入力 ////////////////////

  string s;
  cin >> s;

  //////////////// 出力変数定義 ////////////////

  // 入力をそのまま利用するので、なし

  //////////////////// 処理 ////////////////////

  // 末尾の文字が'e'じゃなかったら、末尾に'e'をつける
  if (s.back()!='e') s += 'e';

  // さらに末尾に'r'をつける
  s += 'r';
  
  //////////////////// 出力 ////////////////////

  cout << s << endl;

  //////////////////// 終了 ////////////////////

  return 0;

}