#include <bits/stdc++.h>
#include <atcoder/all>
using namespace std;
using namespace atcoder;

/////////////////// メイン ///////////////////

int main () {
  
  //////////////////// 入力 ////////////////////
  
  // 整数を1つ用意し、入力を受け取る
  int n;
  cin >> n;

  //////////////// 出力変数定義 ////////////////

  int result = 0;

  //////////////////// 処理 ////////////////////

  // nを2で割って切り上げた値が答え
  // それは、2-1を足してから2で割って切り捨てればよい
  result = (n+1)/2;

  //////////////////// 出力 ////////////////////

  cout << result << endl;

  //////////////////// 終了 ////////////////////

  return 0;

}